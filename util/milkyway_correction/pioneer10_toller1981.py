import numpy as np
def parse(t):
    out={}
    for line in t.splitlines():
        l,v=line.split(':'); vals=[np.nan if x=='-' else float(x) for x in v.split()]
        assert len(vals)==25,(l,len(vals)); out[int(l)]=np.array(vals)
    return out
PB=parse(BLUE); PR=parse(RED)


def surface_brightness_v():
    """{(l, b): mu_V in mag/arcsec^2} where both bands have data"""
    out = {}
    for l in PB:
        for j, b in enumerate(BCOLS):
            Bv, Rv = PB[l][j], PR[l][j]
            if np.isfinite(Bv) and np.isfinite(Rv):
                out[(l, b)] = 27.78 - 2.5*np.log10(Bv**0.45*Rv**0.55)
    return out
